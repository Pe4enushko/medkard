"""Ручной набор: искажения, которые действительно пишут человек и модель.

ЗАЧЕМ ОТДЕЛЬНО ОТ СИНТЕТИКИ. Синтетика ставит случайную букву в случайную
внутреннюю позицию — это не похоже ни на врача, ни на нейронку. Врач меняет
окончание («мексидола»), суффикс внутри лекарственной морфемы («омепрозол»),
приставку, слышит на слух («кардарон»). Нейронка не делает посимвольных
опечаток вовсе: она транслитерирует, приписывает или снимает дозировку и форму,
подставляет МНН вместо торгового. Классы набора:

    inflect    падежное окончание — то, чего синтетика не порождает в принципе:
               _typo ничего не дописывает в конец слова;
    suffix     подмена внутри инвентаря -ол/-ал, -ин/-ен, -ацин/-оцин;
    prefix     приставка снята, добавлена или уехала (L-, Ново-, Ко-);
    tail       снят хвост дозировки/формы — «Креон», «Мезим», «Сиофор»:
               ГОЛОГО названия в реестре нет вовсе, только «Креон® 10000» и
               прочие, поэтому эталон задаётся префиксом;
    dose       наоборот, дозировка дописана к названию, которое её не содержит;
    form       лекформа приклеена спереди: «капли Тизин», «уколы Мексидол»;
    translit   латиница — то, что охотно делает модель;
    mixed      смешанные алфавиты; сюда же «Магне В6», где в реестре латинская B;
    phonetic   на слух: редукция безударных, о↔а, е↔и, э↔е;
    space      дефис и пробелы: «де нол», «коперинева», «А Ц Ц»;
    root       искажён корень, но человек препарат узнаёт;
    dictation  как надиктовано в приём: «конкор пять миллиграмм».

ЭТАЛОН ПРОВЕРЯЕТСЯ ПРИ ЗАГРУЗКЕ. Если запись не разрешается в корпус, набор
падает с перечислением проблемных запросов, а не тихо теряет их: реестр
обновляется, названия из него исчезают, и молчаливая потеря половины набора
выглядела бы как «метод стал лучше».

ВАЖНО про размер корпуса: --limit режет корпус случайной выборкой, и тогда
большинство эталонов в него не попадёт. Ручной набор гонять с --limit 0.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Sequence

from .base import Dataset, Query

DATA = Path(__file__).with_name("handcrafted_ru.json")


class Handcrafted(Dataset):
    key = "handcrafted"
    title = "ручной набор"
    doc = "человеческие и модельные искажения названий, эталон размечен вручную"

    def __init__(self, path: Path | str = DATA) -> None:
        self.path = Path(path)

    def load_raw(self) -> list[dict]:
        return json.loads(self.path.read_text(encoding="utf-8"))["queries"]

    def build(self, corpus: Sequence[dict], rng=None) -> list[Query]:
        from .base import NameIndex

        index = NameIndex(corpus)
        out: list[Query] = []
        missing: list[dict] = []
        for rec in self.load_raw():
            gold = index.resolve(rec["gold_mode"], rec["gold"])
            if not gold:
                missing.append(rec)
                continue
            out.append(Query(rec["kind"], rec["query"], frozenset(gold),
                             rec.get("note", "")))
        if missing:
            lines = "\n".join(
                f"    {r['query']!r} → {r['gold_mode']} {r['gold']!r}" for r in missing)
            raise SystemExit(
                f"ручной набор: {len(missing)} эталонов не найдено в корпусе.\n{lines}\n"
                "Причины по убыванию вероятности: корпус урезан --limit (гонять с 0); "
                "выгрузка ГРЛС другой версии; название исчезло из реестра."
            )
        return out
