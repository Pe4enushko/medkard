#!/usr/bin/env python3
"""
Повторный приём (274н/203н). Два правила, каждое на своей фикстуре — adult и
child.

Тип визита выводится из кода B01.070.011 (repeat), а не задаётся тестом
напрямую.

Отклонение от исходного плана задачи: план предполагал вторую (child)
фикстуру на детерминированной _check_nmu_keyword_contradiction (код .011 +
слово «первичный» в наименовании). Проверено напрямую в исходном коде
(src/audit/formal_structure/validator.py) — _check_nmu_keyword_contradiction
распознаёт только суффиксы .001/.002, тогда как get_visit_types относит к
REPEAT исключительно .011/.012 (см. таблицу в docstring get_visit_types).
Эти два набора суффиксов не пересекаются, то есть NMU_CODE_CONTRADICTION
структурно недостижим ни при каком тексте фикстуры, пока визит
классифицируется как REPEAT — подтверждено и статическим вызовом
_check_nmu_keyword_contradiction() на фикстуре напрямую (вернул None), и
живым прогоном stage 2 (флаг отсутствовал в findings). Поэтому child-
фикстура здесь нацелена на repeat_core_sections_required
(ПОВТОРНЫЙ_ОТСУТСТВУЮТ_ОСНОВНЫЕ_РАЗДЕЛЫ) — второе repeat-специфичное
правило, симметрично тому, как test_audit_primary.py использует два
primary-специфичных правила.

Диагноз J06.9 переименован из «Острый тонзиллит и фарингит» (как в
test_audit_primary.py) в «Острая инфекция верхних дыхательных путей
неуточнённая» — первая формулировка эмпирически тянула за собой
НЕСООТВЕТСТВИЕ_МКБ_И_ТЕКСТА_ДИАГНОЗА (модель последовательно считает, что
текст «тонзиллит и фарингит» соответствует J02.9/J03.9, а не J06.9). Это
применимо ко всем специальностям, не только к педиатрии, как можно было бы
подумать по applies_to.specialties этого правила в rules.json — get_rules()
(validator.py) фильтрует только по visit_types и age_group, специальность
не читается вовсе, так что правило реально доходит до промпта всегда.
Каждая фикстура здесь использует свой dx(...) с разным Детализация (не
общая константа), чтобы контекст одной фикстуры не просачивался в другую.

Обе фикстуры — exact=False, обе задокументированы отдельно ниже; общая
причина — оба repeat-специфичных правила (ПОВТОРНЫЙ_ОТСУТСТВУЕТ_ДИНАМИКА и
ПОВТОРНЫЙ_ОТСУТСТВУЮТ_ОСНОВНЫЕ_РАЗДЕЛЫ) описаны в rules.json почти
синонимично («динамика состояния» и «текущий статус пациента» — по сути
один и тот же контент с точки зрения модели), так что фикстура, лишённая
этого контента, регулярно цепляет оба флага одновременно, а не только
целевой — независимо от формулировки. Ниже — детали по каждой фикстуре и
пройденный путь эмпирической проверки (испробовано 4+ варианта текста на
живых прогонах для каждой).

adult (no_dynamics): убран только раздел с динамикой/сравнением с
предыдущим визитом — добавлен отдельный раздел «Текущий статус» (без
сравнительной лексики), чтобы явно закрыть «текущий статус пациента» из
expectation repeat_core_sections_required и не спровоцировать составной
флаг случайно. С этой правкой ПОВТОРНЫЙ_ОТСУТСТВУЮТ_ОСНОВНЫЕ_РАЗДЕЛЫ больше
не всплывает (было — в самой первой версии без отдельного статус-раздела).
Второй, отдельный источник шума — followup_needed_for_nontrivial_case
(ОТСУТСТВУЕТ_КОНТРОЛЬ_ПРИ_АКТИВНОМ_ПРОЦЕССЕ): J06.9 читается как активный
инфекционный процесс (см. fixtures.py module docstring и
test_audit_primary.py, тот же паттерн на том же диагнозе). Испробовано
несколько явных формулировок разрешения в Рекомендациях («плановый
контрольный осмотр не требуется», «обосновано отсутствие контроля» и т.п.)
— по нескольким живым прогонам подряд правило срабатывает нестабильно (то
есть, то нет) независимо от текста; иногда даёт чистый прогон, иногда нет.
exact=False здесь documents этот же, эмпирически подтверждённый в
test_audit_primary.py класс шума.

child (no_current_status): убран раздел с жалобами/текущим статусом
(«Жалобы», «Динамика»); остаются отдельными абзацами объективный осмотр
(со своим заголовком, не смешан с рекомендациями — смешение эмпирически
давало СМЕШАНЫ_ПЛАН_И_РЕЗУЛЬТАТЫ и путало модель насчёт ОТСУТСТВУЕТ_
ОБЪЕКТИВНЫЙ_ОСМОТР), диагноз (с непустой Детализация — пустая Детализация
эмпирически давала ложный ОТСУТСТВУЕТ_ДИАГНОЗ, хотя запись Диагнозы
непуста) и рекомендации без лекарственной дозировки (иначе НЕПОЛНОЕ_
НАЗНАЧЕНИЕ_ПРЕПАРАТА). Первая версия убирала только «Рекомендации» —
рефлексия показала, что repeat_core_sections_required целится в
[objective_exam, diagnosis, recommendations] по targets в rules.json, но
его expectation-текст (то, что реально видит модель — _format_rules
рендерит только expectation/condition, не targets) вообще не упоминает
рекомендации («текущий статус пациента, объективный осмотр, диагноз/оценка
состояния»), так что при отсутствии только рекомендаций и остальном
полном тексте правило стабильно не срабатывало (3/3 живых прогона — 0
findings). После переноса цели на «текущий статус» (первый пункт
expectation, без отдельного specific-правила-конкурента) флаг стал
срабатывать, но неотделимо от ПОВТОРНЫЙ_ОТСУТСТВУЕТ_ДИНАМИКА (см. выше про
синонимичность двух repeat-правил) и периодически от followup_needed_for_
nontrivial_case и ОТСУТСТВУЕТ_ОБЪЕКТИВНЫЙ_ОСМОТР (модель иногда считает
объективный осмотр «недостаточно структурированным» даже при отдельном
заголовке). exact=False здесь — не пробел в тексте, а подтверждённая
структурная синонимия двух правил на уровне промпта.

Запуск (нужны БД и LLM):  python e2e/tests/audit/test_audit_repeat.py
"""

