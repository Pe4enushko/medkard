#!/usr/bin/env python3
"""
Группа 4 — детерминированный каталог, правила самой записи приёма.

Каталог `src/audit/deterministic/deterministic_rules.json` работает без модели:
на вопрос «есть ли код МКБ» суждение не нужно, и платить за него токенами
нечем. Юниты (`tests/test_deterministic_rules.py`) проверяют сами проверки,
здесь проверяется то, чего они не видят: находка доезжает до
`result.formal.findings` через настоящий `AuditPipeline._audit_visit` и несёт
полный слепок правила. Именно слепок и терялся — после мёржа release находки
каталога приезжали с пустыми полями, а юнит смотрел на валидатор.

Три правила этого скрипта:
  • ПЕРВИЧНЫЙ_ПРИЁМ_БЕЗ_КОДА_МКБ      — первичный приём взрослого без диагноза;
  • ТРАВМА_БЕЗ_КОДА_ВНЕШНЕЙ_ПРИЧИНЫ   — диагноз класса S/T без кода V–Y;
  • НЕ_ЗАПОЛНЕН_НОРМАТИВНЫЙ_МИНИМУМ_ЗАПИСИ — нет раздела формы 025/у.

Все три применяются только к взрослым: форма 025/у адресована взрослому
населению (прил. 2 п. 1 к 274н), детской утверждённой формы нет.

Кейсы стоят `only=False` и идут парами с отрицательными. Стерильной фикстуры
здесь не собрать: детерминированные правила по замыслу перекрываются
формальными — мы переносили проверки наличия из модели в код, — и на карте без
кода МКБ рядом законно встанет ОТСУТСТВУЕТ_ДИАГНОЗ от модели. Отрицательный
кейс — та же карта без дефекта: без него проверка на присутствие не отличила бы
работающее правило от срабатывающего всегда.

Карта `primary_with_icd` служит отрицательным кейсом сразу для двух правил —
кода МКБ и минимума записи. Она проходит полный аудит дважды, и это дешевле
шестой фикстуры: у неё один диагноз, то есть один прогон графа.

Запуск (нужны БД и LLM):
    python e2e/tests/audit/4-test_audit_deterministic_record.py
"""

