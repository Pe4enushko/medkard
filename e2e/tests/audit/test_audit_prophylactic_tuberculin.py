#!/usr/bin/env python3
"""
Профилактический приём — туберкулинодиагностика (Z11.1). Два правила, каждое
на своей фикстуре — adult и child.

Тип визита PROPHYLACTIC_TUBERCULIN приходит из Диагноз.Код == "Z11.1" на
верхнем уровне визита (get_visit_types), не из Услуги — service_code
намеренно пустая строка, услуга остаётся неклассифицированной по NMU-коду
и ключевым словам (в наименовании нет «первичн»/«повторн»/«профилактическ»).

Отклонение от исходного плана задачи: план утверждал, что пустая
service_code делает Услуги «пустым или отсутствующим списком», из-за чего
get_visit_types берёт ранний return для defaulting-в-OTHER (validator.py
~138-142) и итоговый набор становится {PROPHYLACTIC_TUBERCULIN, OTHER}, а не
{PROPHYLACTIC_TUBERCULIN}. Проверено напрямую против validator.py в этой
ветке: base_visit(service_code="", ...) кладёт в Услуги список из ОДНОГО
словаря {"КодЕГИСЗ": "", "Наименование": ...} — это truthy list, поэтому
ранний return (который держится на `if not services`, т.е. на буквально
пустом [] или отсутствии ключа) не срабатывает. Услуга проходит through
per-service цикл, не матчит NMU_RE (пустая строка) и не матчит ни одно из
трёх ключевых слов в наименовании («туберкулинодиагностика» не содержит
«профилактическ»), так что svc_type остаётся None и услуга не добавляет
никакого типа. Итог — voit_types = {PROPHYLACTIC_TUBERCULIN} (проверено
живым вызовом get_visit_types на такой фикстуре: печатает ровно один
элемент). OTHER появляется только когда Услуги буквально [] или ключ
отсутствует вовсе (тоже проверено отдельным вызовом) — ни то, ни другое не
относится к тому, что строит base_visit(). TUBERCULIN ниже — синглтон.
Ни одно правило в rules.json не привязано к visit_types=["other"], так что
это расхождение с планом было бы заметно только на stage 1 (несовпадение
множества типов), не на составе правил.

Оба правила-цели из 190н условны на профиле: ТУБЕРКУЛИН_ОТСУТСТВУЮТ_
ОБЪЕКТИВНЫЕ_ДАННЫЕ и ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ЗАКЛЮЧЕНИЕ — оба required_field
(безусловные), но третье правило той же группы,
ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ОСМОТР_СПЕЦИАЛИСТА_ПРИ_ПАТОЛОГИИ, — conditional:
применимо только «если выявлены патологические состояния... (положительная
или гиперергическая реакция, вираж туберкулиновой пробы)». Обе фикстуры
поэтому описывают физиологическую (отрицательную/нормальную) реакцию на
пробу, чтобы это третье правило не сработало ни в одной из них — иначе
adult-фикстура рисковала бы задеть его вместе с целевым флагом, так как обе
фикстуры по построению не содержат осмотра специалиста.

adult (no_objective_data): раздел «Заключение» присутствует и говорит об
отсутствии патологии, но нигде в карте нет измеримых объективных данных
самой пробы (размер папулы, гиперемия) — только заключительная фраза без
результата измерения. Изолирует ТУБЕРКУЛИН_ОТСУТСТВУЮТ_ОБЪЕКТИВНЫЕ_ДАННЫЕ,
не задевая ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ЗАКЛЮЧЕНИЕ (заключение есть).

child (no_conclusion): раздел «Объективный осмотр» содержит полные
измеримые данные пробы (папула 8 мм, гиперемия 2 мм, без везикул и
некроза — читается как физиологическая реакция, не патология), но нигде в
карте нет итогового заключения о наличии/отсутствии патологических
состояний. Изолирует ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ЗАКЛЮЧЕНИЕ, не задевая
ТУБЕРКУЛИН_ОТСУТСТВУЮТ_ОБЪЕКТИВНЫЕ_ДАННЫЕ (данные пробы есть).

Диагноз Z11.1 — «Специальное скрининговое обследование с целью выявления
туберкулёза органов дыхания» (плановый скрининг, не активная инфекция), с
непустой Детализация в обеих фикстурах — пустая Детализация в других файлах
серии эмпирически давала ложный ОТСУТСТВУЕТ_ДИАГНОЗ.

followup_needed_for_nontrivial_case (ОТСУТСТВУЕТ_КОНТРОЛЬ_ПРИ_АКТИВНОМ_
ПРОЦЕССЕ) — источник шума в test_audit_primary.py/test_audit_repeat.py — по
rules.json applies_to.visit_types значится только для ["primary", "repeat"],
структурно вне области действия здесь; подтверждено также эмпирически — ни
разу не встретилось за все живые прогоны ниже.

Оба кейса — exact=True (без исключений): 5 подряд чистых живых прогонов
всего файла (по одному "exactly one flag" на кейс на каждый прогон, 10/10),
без единого лишнего флага — включая НЕСООТВЕТСТВИЕ_УСЛУГИ_И_ВИЗИТА (специальности
«Терапевт»/«Педиатр» + плановая туберкулинодиагностика не читались моделью
как противоречие ни разу) и ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ОСМОТР_СПЕЦИАЛИСТА_ПРИ_
ПАТОЛОГИИ (условие правила — патологическая реакция — не выполняется ни в
одной из фикстур).

Запуск (нужны БД и LLM):  python e2e/tests/audit/test_audit_prophylactic_tuberculin.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fixtures import base_visit, dx  # noqa: E402
from harness import Case, VisitType, run_cases  # noqa: E402

TUBERCULIN = {VisitType.PROPHYLACTIC_TUBERCULIN}
Z11_1_NAME = "Специальное скрининговое обследование с целью выявления туберкулёза органов дыхания"


def _tuberculin_visit(
    guid: str, specialty: str, age: int, inspection: list[tuple[str, str]]
) -> dict:
    visit = base_visit(
        guid=guid,
        service_code="",
        service_name="Туберкулинодиагностика (внутрикожная проба с туберкулином)",
        specialty=specialty,
        age=age,
        diagnoses=[
            dx(
                "Z11.1",
                Z11_1_NAME,
                detail="Плановая туберкулинодиагностика в рамках ежегодного скрининга.",
            )
        ],
        inspection=inspection,
    )
    # get_visit_types reads Диагноз.Код at the visit's top level for the
    # PROPHYLACTIC_TUBERCULIN branch — a separate key from Диагнозы[].КодМКБ.
    visit["Диагноз"] = {"Код": "Z11.1"}
    return visit


no_objective_data = _tuberculin_visit(
    "e2e-audit-tuberculin-adult-no-objective-data",
    "Терапевт",
    45,
    [
        ("Жалобы", "Жалоб не предъявляет, проба проводится в плановом порядке."),
        (
            "Заключение",
            "Патологических состояний, свидетельствующих о наличии туберкулёза, не выявлено.",
        ),
        ("Рекомендации", "Очередная туберкулинодиагностика через 12 месяцев."),
    ],
)

no_conclusion = _tuberculin_visit(
    "e2e-audit-tuberculin-child-no-conclusion",
    "Педиатр",
    8,
    [
        (
            "Жалобы",
            "Жалоб не предъявляет. Осмотр проведён в сопровождении матери, "
            "Петровой Ольги Ивановны.",
        ),
        (
            "Объективный осмотр",
            "Место введения туберкулина на левом предплечье: папула 8 мм, гиперемия вокруг "
            "папулы 2 мм, везикул и некроза нет.",
        ),
        ("Рекомендации", "Очередная туберкулинодиагностика через 12 месяцев."),
    ],
)

CASES = [
    Case(
        name="взрослый: нет объективных данных пробы",
        visit=no_objective_data,
        expect="ТУБЕРКУЛИН_ОТСУТСТВУЮТ_ОБЪЕКТИВНЫЕ_ДАННЫЕ",
        visit_types=TUBERCULIN,
    ),
    Case(
        name="ребёнок: нет заключения по пробе",
        visit=no_conclusion,
        expect="ТУБЕРКУЛИН_ОТСУТСТВУЕТ_ЗАКЛЮЧЕНИЕ",
        visit_types=TUBERCULIN,
    ),
]


if __name__ == "__main__":
    try:
        sys.exit(asyncio.run(run_cases("Аудит: туберкулинодиагностика", CASES)))
    except KeyboardInterrupt:
        sys.exit(130)
