#!/usr/bin/env python3
"""
Лабораторные/инструментальные исследования и вмешательства (464н, A-коды).
Два правила, каждое на своей фикстуре — adult и child.

Тип визита выводится из A05.010.006 (ЭКГ) — A-префикс всегда даёт
LAB_RESEARCH_INTERVENTION (validator.py). NMU_RE требует три группы цифр
2-3-3 (validator.py: `^[ABАВ]\d{2}\.\d{3}\.\d{3}(?:\.\d{3})?$`), поэтому
средняя группа — «010», не «10».

В child-фикстуре заключение по ЭКГ присутствует, иначе задело бы соседнее
ecg_functional_description_and_conclusion вместе с целевым дублированием.

Специальность — «Врач функциональной диагностики», не «Кардиолог»: первая
попытка со специальностью «Кардиолог» стабильно (обе фикстуры, оба живых
прогона) тянула НЕСООТВЕТСТВИЕ_УСЛУГИ_И_ВИЗИТА — модель читает «кардиолог +
ЭКГ + диагноз ОРВИ (не кардиологический)» как несогласованность профиля
помощи и диагноза, даже когда сама услуга (ЭКГ) специальности соответствует.
Функциональная диагностика выполняет ЭКГ по направлению лечащего врача вне
зависимости от диагноза направившего врача, так что это несоответствие не
возникает. Добавлен явный блок «Направление», объясняющий, что ЭКГ
назначена лечащим терапевтом/педиатром в рамках наблюдения по поводу ОРВИ —
делает связь диагноз → направление → услуга последовательной по всей карте.

Первая версия дублирования в child-фикстуре ставила рядом «Жалобы» и
«Жалобы со слов законного представителя» с одинаковым текстом — целевой флаг
срабатывал, но вместе с ним стабильно (оба живых прогона) шёл
НЕСООТВЕТСТВИЕ_УСЛУГИ_И_ВИЗИТА: врач функциональной диагностики,
принимающий жалобы пациента напрямую, читается моделью как несогласованность
роли специалиста с профилем визита. Дублирование перенесено в блок
результата — «Протокол ЭКГ» и «Заключение» с идентичным текстом, — что
специалисту функциональной диагностики соответствует и оставляет только
целевой флаг.

Оба кейса — exact=True (без исключений): 4 подряд чистых живых прогона всего
файла после финальной правки фикстур (специальность «Врач функциональной
диагностики» + блок «Направление» + перенос дублирования в результат ЭКГ).

Запуск (нужны БД и LLM):  python e2e/tests/audit/test_audit_lab_research_intervention.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fixtures import base_visit, dx  # noqa: E402
from harness import Case, VisitType, run_cases  # noqa: E402

LAB = {VisitType.LAB_RESEARCH_INTERVENTION}
SERVICE_CODE = "A05.010.006"
J06_9 = dx("J06.9", "Острая инфекция верхних дыхательных путей неуточнённая")

no_conclusion = base_visit(
    guid="e2e-audit-lab-adult-no-conclusion",
    service_code=SERVICE_CODE,
    service_name="Электрокардиография",
    specialty="Врач функциональной диагностики",
    age=45,
    diagnoses=[J06_9],
    inspection=[
        (
            "Направление",
            "Направлен лечащим терапевтом на плановую электрокардиографию в рамках "
            "текущего наблюдения по поводу острой инфекции верхних дыхательных путей.",
        ),
        (
            "Протокол ЭКГ",
            "Ритм синусовый, ЧСС 72 в минуту, электрическая ось не отклонена, интервалы PQ, QRS, QT в пределах нормы.",
        ),
    ],
)

duplicate_blocks = base_visit(
    guid="e2e-audit-lab-child-duplicate-blocks",
    service_code=SERVICE_CODE,
    service_name="Электрокардиография",
    specialty="Врач функциональной диагностики",
    age=8,
    diagnoses=[J06_9],
    inspection=[
        (
            "Направление",
            "Направлен лечащим педиатром на плановую электрокардиографию в рамках "
            "текущего наблюдения по поводу острой инфекции верхних дыхательных путей. "
            "Осмотр проведён в сопровождении матери, Сидоровой Марии Петровны.",
        ),
        (
            "Протокол ЭКГ",
            "Ритм синусовый, ЧСС 100 в минуту, без патологии. Заключение: возрастная норма.",
        ),
        (
            "Заключение",
            "Ритм синусовый, ЧСС 100 в минуту, без патологии. Заключение: возрастная норма.",
        ),
    ],
)

CASES = [
    Case(
        name="взрослый: нет заключения по ЭКГ",
        visit=no_conclusion,
        expect="ФУНКЦИОНАЛЬНОЕ_ИССЛЕДОВАНИЕ_НЕПОЛНОЕ",
        visit_types=LAB,
    ),
    Case(
        name="ребёнок: дублирование смысловых блоков",
        visit=duplicate_blocks,
        expect="ДУБЛИРОВАНИЕ_СМЫСЛОВЫХ_БЛОКОВ",
        visit_types=LAB,
    ),
]


if __name__ == "__main__":
    try:
        sys.exit(asyncio.run(run_cases("Аудит: исследования и вмешательства", CASES)))
    except KeyboardInterrupt:
        sys.exit(130)
