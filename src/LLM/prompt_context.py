"""
prompt_context.py — блоки пользовательского сообщения, общие для чекеров.

Здесь живёт только то, что подставляется в каждый запрос одинаково и потому
не должно расходиться между контурами: системные промпты лежат в ``prompts/``
и от карты не зависят, а этот модуль даёт куски, зависящие от самой записи.
"""

from __future__ import annotations

from datetime import date

_TODAY_TEMPLATE = (
    "## Сегодняшний день\n"
    "{day} — дата этого приёма, считай её сегодняшним днём. Всё, что записано "
    "более ранней датой, уже произошло; более поздней — запланировано. "
    "Не объявляй дату ошибкой или опечаткой только потому, что она кажется тебе будущей."
)


def today_block(visit_date: date | None) -> str:
    """Блок «сегодня» для чекера, судящего даты внутри записи.

    Своего представления о текущей дате у модели нет — есть представление,
    оставшееся от обучения, и оно отстаёт. На выгрузке Алёнки за 20.08.2026
    это дало ложные замечания в шести картах из семидесяти: год приёма чекер
    объявлял «будущим, возможно опечаткой», а уже проставленный результат
    Диаскинтеста от 15.09.2025 — «сроком, который ещё не наступил».

    Без даты приёма блок пустой: выдуманная точка отсчёта хуже отсутствующей.
    """
    if visit_date is None:
        return ""
    return _TODAY_TEMPLATE.format(day=visit_date.strftime("%d.%m.%Y"))
