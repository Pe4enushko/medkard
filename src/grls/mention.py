"""Упоминание препарата из карты → запросы к реестру. Детерминированно, без модели.

Раньше нормализацию делала та же модель, что извлекала упоминания: у неё было
поле `normalized` «краткое нормализованное название для поиска».  Задача не
определена, и на прогоне 2026-08-23 модель на 90 упоминаниях сделала три разные
вещи — 37 оставила как есть, 36 заменила на МНН, 17 сократила, — причём
несогласованно с собой: «Капотен → каптоприл» и «капотен → Капотен» в одном
прогоне.  Там, где МНН не существует (БАДы) или вход обрублен опечаткой, она
заполняла поле выдумкой: «Армолипид → Армолипин» (БАД подменён торговым
названием амлодипина), «Эльжина → элюцин», «Уросо → Уросан».

Поэтому перевод в МНН отсюда убран целиком, а не «улучшен»: реестр сам знает
соответствие торгового наименования и МНН, `lookup_medicine` ищет сперва по
одному, потом по другому.  Каждая верная замена модели нашлась бы и по тому,
что написал врач; каждая неверная — чистая потеря.

Возвращается не одна строка, а список кандидатов от точного к широкому: у
упоминания бывает две законные формы записи, и выбирать между ними вслепую
хуже, чем попробовать обе.

Одно исключение из «никакой транслитерации» — буквы витаминов: набор закрыт
(A/B/C/D/E/K), встречается системно, и латинская D с кириллической Д на письме
взаимозаменяемы.  Обе формы уходят в поиск отдельными кандидатами.

Известный пробел: «L-тироксин» латиницей против «Л-Тироксин» в реестре здесь не
чинится.  Там набор открыт, и транслитерация без замера была бы угадыванием; это
работа триграммного слоя, и сперва надо понять, почему он молчит
(см. grls-fuzzy-probe.sql).
"""
from __future__ import annotations

import re

from grls.normalize import normalize_query

# Дозировка: число с единицей либо «№2». Голое число не трогаем — в «Омега 3»
# и «Мабелль-плюс» цифра часть названия, а не доза.
_DOSAGE_RE = re.compile(
    r"\b\d+(?:[.,]\d+)?\s*(?:%|мг|мкг|мл|г|ме|ед|тыс|млн)\b|№\s*\d+|\d+(?:[.,]\d+)?\s*%"
)

_PAREN_RE = re.compile(r"\(([^)]*)\)")

# «пенка для умывания», «спрей мист для тела», «крем для лица».
_PURPOSE_RE = re.compile(r"\bдля\s+\S+")

# Форма выпуска, приклеенная к названию: «Липобейз крем», «Далацин гель 1%».
_FORM_WORDS = frozenset({
    "таблетки", "таблетка", "таб", "капсулы", "капсула", "капс", "драже",
    "гель", "крем", "мазь", "паста", "эмульсия", "лосьон", "пенка", "пена",
    "мист", "спрей", "аэрозоль", "раствор", "суспензия", "сироп", "капли",
    "свечи", "суппозитории", "ампулы", "порошок", "гранулы", "саше", "стик",
    "пластырь", "настойка", "шампунь", "сбор", "концентрат", "лиофилизат",
})

# Не название препарата, а вид изделия или класс, которым врач его обозначил:
# «ВМС «Мирена»», «КОК «Джес»», «НПВС свечи «Индометацин»», «Препараты Йода».
_DEVICE_WORDS = frozenset({
    "вмс", "спираль", "кок", "нпвс", "ипп", "бад", "препарат", "препараты",
    "комплекс", "комплексы",
})

# «Таб.Юнидокс-солютаб», «таб.фолиевая кислота»: врач лепит сокращение формы к
# названию через точку, и без разлепления в реестр уходит несуществующее слово.
_GLUED_DOT_RE = re.compile(r"(?<=[а-яёa-z])\.(?=[а-яёa-z])", re.IGNORECASE)

# Витамин пишут четырьмя способами: «Вит Д», «Вит. D», «Витамин Д», «Витамин D».
# Реестр хранит один. Буквы латинские и кириллические здесь неразличимы на глаз и
# взаимозаменяемы на письме, поэтому обе формы уходят в поиск как отдельные
# кандидаты — угадывать, какую имел в виду врач, нечем.
#
# Набор закрытый и короткий: это единственное место, где транслитерация в названии
# препарата встречается системно. Общая транслитерация («L-тироксин» ↔
# «Л-Тироксин») сюда НЕ добавлена намеренно — там набор открыт, и без замера это
# было бы угадыванием (см. docs/tech-debt.md).
_VITAMIN_RE = re.compile(r"\b(?:вит|витамин)\.?\s*([a-zа-я]|[a-zа-я]\d+)\b", re.IGNORECASE)
_VITAMIN_LETTERS = {"a": "а", "а": "a", "b": "в", "в": "b", "c": "с", "с": "c",
                    "d": "д", "д": "d", "e": "е", "е": "e", "k": "к", "к": "k"}

_MIN_QUERY_LEN = 3


def _vitamin_forms(text: str) -> list[str]:
    """«вит д» → [«витамин д», «витамин d»]. Пусто, если это не витамин."""
    match = _VITAMIN_RE.search(text)
    if not match:
        return []
    letter = match.group(1).lower()
    head, tail = letter[0], letter[1:]
    out = [f"витамин {letter}"]
    twin = _VITAMIN_LETTERS.get(head)
    if twin:
        out.append(f"витамин {twin}{tail}")
    return out


def _strip_noise(text: str) -> str:
    """Убрать дозировку, назначение, форму выпуска и класс. Название остаётся."""
    text = _DOSAGE_RE.sub(" ", text)
    text = _PURPOSE_RE.sub(" ", text)
    text = _GLUED_DOT_RE.sub(" ", text)
    words = [
        word
        for word in (w.strip(".,;") for w in text.split())
        if word and word not in _FORM_WORDS and word not in _DEVICE_WORDS
    ]
    return " ".join(words)


def search_candidates(as_written: str) -> list[str]:
    """Запросы к реестру по одному упоминанию, от точного к широкому.

    Порядок значим: первым идёт очищенное название — у него больше всего шансов
    на точное совпадение.  Затем содержимое скобок: врач пишет туда второе имя
    того же препарата («Моксонидин (Физиотенз)»), и оно ничем не хуже первого.
    Последней — исходная строка целиком: она нужна слою «вхождение», который
    ищет название реестра внутри запроса и потому переживает мусор вокруг.
    """
    outside = normalize_query(_PAREN_RE.sub(" ", as_written))
    stripped = _strip_noise(outside)
    # В скобках бывает перечень: «Препараты Йода (Йодомарин, Калия йодид)» —
    # это два разных препарата, а не одно название с запятой.
    parens = [
        normalize_query(_strip_noise(normalize_query(part)))
        for group in _PAREN_RE.findall(as_written)
        for part in group.split(",")
    ]
    whole = normalize_query(as_written)

    out: list[str] = []
    for candidate in (*_vitamin_forms(stripped), stripped, *parens, outside, whole):
        if len(candidate) >= _MIN_QUERY_LEN and candidate not in out:
            out.append(candidate)
    return out
