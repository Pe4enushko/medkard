-- Migration 030: diag_errors — журнал наших аварий по карте, отдельно от
-- результата аудита.
--
-- Деградация графа (упавший судья, пустой ответ модели) писалась в
-- diag_result[].errors. Эта строка целиком уезжает в реплику движка и попадает
-- агенту медчека как есть: он читает её как факт о карте и несёт нашу
-- внутреннюю ошибку врачу. В отчёт она тоже попадала — блоком [ДЕГРАДАЦИЯ]
-- с сырым текстом исключения.
--
-- Колонку не выбирает ни один запрос pull-API (см.
-- tests/test_diag_errors_stay_in_medkard.py), поэтому за пределы медкарда она
-- не выходит. NULL означает «ничего не падало».
--
-- Старые строки чистит scripts/hacks/backfill-guideline-meta.py: он вынимает
-- errors из diag_result и переносит их сюда.

ALTER TABLE done_cards
    ADD COLUMN IF NOT EXISTS diag_errors TEXT[];

COMMENT ON COLUMN done_cards.diag_errors IS
    'Аварии аудита по карте: «<код МКБ>: <что упало>». Внутреннее, наружу не отдаётся.';
